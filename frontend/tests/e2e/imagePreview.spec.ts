import { expect, test } from '@playwright/test'

test('生成图片可缩放、拖动、原尺寸还原，重新打开恢复适配', async ({ page }) => {
  await page.goto('/tests/image-preview-fixture.html')
  await page.locator('.media-frame').click()
  const viewer = page.locator('.workspace-image-viewer')
  await expect(viewer.getByRole('button', { name: '放大', exact: true })).toBeEnabled()
  const initial = await viewer.locator('.zoom-text').innerText()
  await viewer.getByRole('button', { name: '放大', exact: true }).click()
  await expect(viewer.locator('.zoom-text')).not.toHaveText(initial)
  await viewer.getByRole('button', { name: '缩小', exact: true }).click()
  await expect(viewer.locator('.zoom-text')).toHaveText(initial)
  await viewer.getByRole('button', { name: '1:1', exact: true }).click()
  await expect(viewer.locator('.zoom-text')).toHaveText('100%')
  // 原始像素尺寸不受 CSS max-width 影响，放大后拖动必须改变平移量。
  await expect(viewer.locator('img')).toHaveCSS('width', '1600px')
  const stage = viewer.locator('.image-stage')
  const box = (await stage.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 40)
  await page.mouse.up()
  await expect(viewer.locator('.image-wrapper')).not.toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await page.mouse.wheel(0, -120)
  await expect(viewer.locator('.zoom-text')).toHaveText('125%')
  await stage.press('0')
  await expect(viewer.locator('.zoom-text')).toHaveText(initial)
  await page.keyboard.press('Escape')
  await expect(viewer).toHaveCount(0)
  await page.locator('.media-frame').click()
  await expect(viewer.locator('.zoom-text')).toHaveText(initial)
})

test('窄屏图片附件复用缩放查看器，工具栏不横向溢出', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/tests/image-preview-fixture.html')
  await page.locator('.attachment-visual').click()
  const viewer = page.locator('.workspace-image-viewer')
  await expect(viewer.getByRole('button', { name: '放大', exact: true })).toBeEnabled()
  await viewer.getByRole('button', { name: '放大', exact: true }).click()
  await viewer.getByRole('button', { name: '适应', exact: true }).click()
  const toolbar = viewer.locator('.image-toolbar')
  expect(await toolbar.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await expect(viewer.locator('.image-stage')).toBeVisible()
})
